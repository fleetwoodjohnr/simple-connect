export function resolveTerminalTheme(name: string): ITheme {
  if (name === "auto" || !TERMINAL_THEMES[name]) {
    const light = document.documentElement.dataset.theme === "light";
    return TERMINAL_THEMES[light ? "paper" : "graphite"].theme;
  }
  return TERMINAL_THEMES[name].theme;
}
