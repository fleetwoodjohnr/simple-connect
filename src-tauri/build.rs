/// Core and plugin permissions the webview needs. No shell, fs or http access.
const CORE_PERMISSIONS: &[&str] = &[
    "core:event:default",
    "core:window:allow-set-fullscreen",
    "core:window:allow-is-fullscreen",
    "dialog:allow-open",
    "dialog:allow-save",
    "dialog:allow-ask",
    "updater:default",
    "process:allow-restart",
];

fn main() {
    let permissions: Vec<String> =
        CORE_PERMISSIONS.iter().map(|p| p.to_string()).chain(COMMANDS.iter().map(|c| format!("allow-{}", c.replace('_', "-")))).collect();
    let capability = serde_json::json!({
        "$schema": "../gen/schemas/desktop-schema.json",
        "identifier": "main",
        "description": "Generated by build.rs from COMMANDS. Do not edit.",
        "windows": ["main"],
        "permissions": permissions,
    });
    let text = serde_json::to_string_pretty(&capability).expect("serialize capability") + "\n";
    let path = "capabilities/main.json";
    if std::fs::read_to_string(path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(path, text).expect("write capability");
    }

    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)))
        .expect("failed to run tauri-build");
}
